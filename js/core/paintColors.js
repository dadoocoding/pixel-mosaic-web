export const PAINT_BRAND_NAMES = ["Sherwin-Williams", "Behr", "Krylon"];

function rgbToHexLocal([r, g, b]) {
  const c = v => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, "0");
  return `#${c(r)}${c(g)}${c(b)}`;
}

// Lab-space coordinates of every brand's palette, computed once and cached
// (there are 1,200+ colors total across all three brands -- converting
// them to Lab on every match call would be wasteful for something that
// never changes at runtime).
const _brandLabCache = new Map();

function brandLab(brand) {
  if (!_brandLabCache.has(brand)) {
    const lab = PAINT_BRANDS[brand].map(([, , rgb]) => rgbToLab(rgb));
    _brandLabCache.set(brand, lab);
  }
  return _brandLabCache.get(brand);
}

function labDistSq(a, b) {
  const dl = a[0] - b[0], da = a[1] - b[1], db = a[2] - b[2];
  return dl * dl + da * da + db * db;
}

/**
 * For each [r,g,b] in colors, find the nearest color in PAINT_BRANDS[brand]
 * by CIE Lab distance (same perceptual metric as quantize.js's fixed-
 * palette matching). Returns a list of {name, code, hex, rgb}, one per
 * input color, in order.
 */
export function nearestPaintMatches(colors, brand) {
  if (!colors.length) return [];
  const entries = PAINT_BRANDS[brand];
  const labPalette = brandLab(brand);

  return colors.map((rgb) => {
    const queryLab = rgbToLab(rgb);
    let bestIdx = 0, bestDist = Infinity;
    for (let i = 0; i < labPalette.length; i++) {
      const d = labDistSq(queryLab, labPalette[i]);
      if (d < bestDist) { bestDist = d; bestIdx = i; }
    }
    const [name, code, matchRgb] = entries[bestIdx];
    return { name, code, hex: rgbToHexLocal(matchRgb), rgb: matchRgb };
  });
}

/**
 * For each [r,g,b] in colors, find the nearest color in *every* brand plus
 * the single best match overall (the brand/color whose Lab distance is
 * smallest across all brands combined -- comparable directly since Lab
 * distance doesn't depend on which brand a color came from). Returns a
 * list of objects, one per input color:
 * {"Sherwin-Williams": {...}, "Behr": {...}, "Krylon": {...},
 *  best: {brand, name, code, hex}}
 */
export function nearestPaintMatchesAllBrands(colors) {
  if (!colors.length) return [];
  const perBrand = {};
  for (const brand of PAINT_BRAND_NAMES) perBrand[brand] = nearestPaintMatches(colors, brand);

  return colors.map((rgb, i) => {
    const row = {};
    let bestBrand = null, bestMatch = null, bestDist = Infinity;
    const queryLab = rgbToLab(rgb);
    for (const brand of PAINT_BRAND_NAMES) {
      const match = perBrand[brand][i];
      row[brand] = match;
      const d = labDistSq(queryLab, rgbToLab(match.rgb));
      if (d < bestDist) { bestDist = d; bestBrand = brand; bestMatch = match; }
    }
    row.best = { brand: bestBrand, name: bestMatch.name, code: bestMatch.code, hex: bestMatch.hex };
    return row;
  });
}

/** "Name (Code)" for CSV display, or just "Name" when there's no code
 * (true for every Krylon entry, since Krylon doesn't publish color codes). */
export function formatMatch(match) {
  return match.code ? `${match.name} (${match.code})` : match.name;
}

/** "Brand: Name (Code)" -- formatMatch plus which brand it came from,
 * since the overall-best match can be any of the three. */
export function formatBestMatch(best) {
  return `${best.brand}: ${formatMatch(best)}`;
}
